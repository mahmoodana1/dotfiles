#!/usr/bin/env python3
"""Generate yazi's colours from nvim's actual theme.

Reads the live Catppuccin palette out of nvim (so the LIGHTEN / VIVID / BLEND
knobs in ~/.config/nvim/lua/plugins/ui.lua carry over) and writes:
  ~/.config/yazi/theme.toml  yazi's theme, mapped the way nvim uses each colour
  ~/.config/yazi/foot.ini    foot config for the yazi window: your foot.ini
                             with nvim's background, so yazi sits on the same
                             base as the editor

Re-run after changing ui.lua:  python3 ~/.config/yazi/gen-theme.py
"""
import json
import os
import subprocess

HOME = os.path.expanduser("~")
OUT = f"{HOME}/.config/yazi/theme.toml"
FOOT = f"{HOME}/.config/yazi/foot.ini"


def nvim_lua(code):
    return subprocess.run(
        ["nvim", "--headless", "-c", "lua " + code, "-c", "qa!"],
        capture_output=True, text=True, timeout=30, check=True,
    ).stdout.strip()


p = json.loads(nvim_lua('io.stdout:write(vim.json.encode(require("catppuccin.palettes").get_palette("mocha")))'))
cursorline = nvim_lua('io.stdout:write(string.format("#%06x", vim.api.nvim_get_hl(0, {name="CursorLine", link=false}).bg))')

# Names follow nvim's palette so it's clear where each colour comes from.
base, mantle = p["base"], p["mantle"]
surface0, surface1 = p["surface0"], p["surface1"]
text, sub0, ov1, ov2 = p["text"], p["subtext0"], p["overlay1"], p["overlay2"]
blue, mauve, red, green = p["blue"], p["mauve"], p["red"], p["green"]
yellow, pink, teal = p["yellow"], p["pink"], p["teal"]

# Nerd Font half-circles, the same caps lualine uses.
L, R = "", ""

theme = f'''# GENERATED by ~/.config/yazi/gen-theme.py from nvim's Catppuccin palette.
# Edit the generator (or nvim's ui.lua and re-run it), not this file.

[mgr]
cwd = {{ fg = "{blue}", bold = true }}
find_keyword  = {{ fg = "{text}", bg = "#465f73", bold = true }}
find_position = {{ fg = "{ov2}", italic = true }}
symlink_target = {{ fg = "{ov2}", italic = true }}

marker_symbol   = "▎"
marker_copied   = {{ fg = "{green}" }}
marker_cut      = {{ fg = "{red}" }}
marker_marked   = {{ fg = "{teal}" }}
marker_selected = {{ fg = "{mauve}" }}

count_copied   = {{ fg = "{base}", bg = "{green}" }}
count_cut      = {{ fg = "{base}", bg = "{red}" }}
count_selected = {{ fg = "{base}", bg = "{mauve}" }}

border_symbol = "│"
border_style  = {{ fg = "{surface1}" }}

# Hovered row = nvim CursorLine, with lualine's rounded ends.
[indicator]
current = {{ bg = "{cursorline}", bold = true }}
parent  = {{ bg = "{cursorline}" }}
preview = {{ bg = "{cursorline}" }}
padding = {{ open = "{L}", close = "{R}" }}

[tabs]
active    = {{ fg = "{mantle}", bg = "{blue}", bold = true }}
inactive  = {{ fg = "{blue}", bg = "{surface0}" }}
sep_inner = {{ open = "{L}", close = "{R}" }}
sep_outer = {{ open = "{L}", close = "{R}" }}

# Modes = lualine catppuccin-mocha: normal blue, select = visual mauve.
[mode]
normal_main = {{ fg = "{mantle}", bg = "{blue}", bold = true }}
normal_alt  = {{ fg = "{blue}", bg = "{surface0}" }}
select_main = {{ fg = "{base}", bg = "{mauve}", bold = true }}
select_alt  = {{ fg = "{mauve}", bg = "{surface0}" }}
unset_main  = {{ fg = "{base}", bg = "{red}", bold = true }}
unset_alt   = {{ fg = "{red}", bg = "{surface0}" }}

[status]
overall   = {{ fg = "{sub0}" }}
sep_left  = {{ open = "{L}", close = "{R}" }}
sep_right = {{ open = "{L}", close = "{R}" }}
perm_sep   = {{ fg = "{surface1}" }}
perm_type  = {{ fg = "{blue}" }}
perm_read  = {{ fg = "{yellow}" }}
perm_write = {{ fg = "{red}" }}
perm_exec  = {{ fg = "{green}" }}
progress_label  = {{ fg = "{text}", bold = true }}
progress_normal = {{ fg = "{blue}", bg = "{surface0}" }}
progress_error  = {{ fg = "{red}", bg = "{surface0}" }}

# Popups = nvim floats (mantle background, blue FloatBorder); the key list
# = which-key (keys blue, descriptions pink).
[which]
mask            = {{ bg = "{mantle}" }}
cand            = {{ fg = "{blue}", bold = true }}
rest            = {{ fg = "{ov1}" }}
desc            = {{ fg = "{pink}" }}
separator       = "  "
separator_style = {{ fg = "{surface1}" }}

[confirm]
border  = {{ fg = "{blue}" }}
title   = {{ fg = "{sub0}" }}
btn_yes = {{ fg = "{mantle}", bg = "{blue}", bold = true }}
btn_no  = {{ fg = "{ov2}" }}

[spot]
border   = {{ fg = "{blue}" }}
title    = {{ fg = "{sub0}" }}
tbl_col  = {{ fg = "{blue}" }}
tbl_cell = {{ fg = "{text}", bg = "{surface1}" }}

[notify]
title_info  = {{ fg = "{teal}" }}
title_warn  = {{ fg = "{yellow}" }}
title_error = {{ fg = "{red}" }}

[pick]
border   = {{ fg = "{blue}" }}
active   = {{ fg = "{text}", bg = "{surface0}", bold = true }}
inactive = {{ fg = "{ov2}" }}

[input]
border   = {{ fg = "{blue}" }}
title    = {{ fg = "{sub0}" }}
value    = {{ fg = "{text}" }}
selected = {{ bg = "{surface1}" }}

[cmp]
border   = {{ fg = "{blue}" }}
active   = {{ fg = "{text}", bg = "{surface0}" }}
inactive = {{ fg = "{ov2}" }}

[tasks]
border  = {{ fg = "{blue}" }}
title   = {{ fg = "{sub0}" }}
hovered = {{ fg = "{text}", bg = "{surface0}", bold = true }}

[help]
border  = {{ fg = "{blue}" }}
chord   = {{ fg = "{blue}", bold = true }}
action  = {{ fg = "{pink}" }}
hovered = {{ bg = "{surface0}", bold = true }}

# Git = gitsigns: the same ▎ bar, green added / yellow changed / red deleted.
[git]
modified  = {{ fg = "{yellow}" }}
unstaged  = {{ fg = "{yellow}" }}
updated   = {{ fg = "{yellow}" }}
staged    = {{ fg = "{green}" }}
added     = {{ fg = "{green}" }}
untracked = {{ fg = "{teal}" }}
deleted   = {{ fg = "{red}" }}
ignored   = {{ fg = "{surface1}" }}
unstaged_sign  = "▎"
updated_sign   = "▎"
staged_sign    = "▎"
added_sign     = "▎"
untracked_sign = "▎"
deleted_sign   = "▁"
ignored_sign   = " "
clean_sign     = " "

# Folder icons in nvim's Directory blue (named ones like Downloads keep
# yazi's own icon).
[icon]
prepend_conds = [
	{{ if = "dir & hovered", text = "\\uf07c", fg = "{blue}" }},
	{{ if = "dir", text = "\\uf07b", fg = "{blue}" }},
]

# Folders = nvim Directory (blue), files = Normal text, dotfiles = Comment.
[filetype]
rules = [
	{{ mime = "vfs/{{absent,stale}}", fg = "{surface1}" }},
	{{ url = "*", is = "orphan", fg = "{red}", italic = true }},
	{{ url = "*", is = "dummy", fg = "{red}" }},
	{{ url = ".*/", fg = "{ov2}" }},
	{{ url = "*/", fg = "{blue}" }},
	{{ url = ".*", fg = "{ov2}" }},
	{{ url = "*", is = "exec", fg = "{green}" }},
	{{ url = "*", fg = "{text}" }},
]
'''

foot = f'''# GENERATED by ~/.config/yazi/gen-theme.py: your foot.ini with nvim's colours.
[main]
include={HOME}/.config/foot/foot.ini

[colors-dark]
background={base[1:]}
foreground={text[1:]}
selection-background={surface1[1:]}
selection-foreground={text[1:]}
'''

for path, body in ((OUT, theme), (FOOT, foot)):
    with open(path + ".tmp", "w") as f:
        f.write(body)
    os.replace(path + ".tmp", path)
